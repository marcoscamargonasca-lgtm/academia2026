create table if not exists public.alumnos (
id bigint generated by default as identity primary key,
created_at timestamptz default now(),
nombre text not null, edad integer not null, whatsapp text not null,
email text, nivel text not null, mensaje text);
alter table public.alumnos enable row level security;
create policy "registro_publico_alumnos" on public.alumnos for insert to anon with check (true);
